#!/usr/bin/env python3
"""Parameter-matched SAE comparison (main text, "Capacity analysis").

For every encoder x activation (TopK, BatchTopK, JumpReLU) and dataset, reports

    Delta metric = metric(parameter-matched SAE) - metric(DualSAE)

for R^2, MS, Pur., KNN and LP, where both terms are seed means from the collector's long CSV
(methods ``<act>_pmatch`` and the corresponding ``dual_*``); negative values favour DualSAE.
The parameter counts are computed by instantiating the model classes: ``Par.`` is the number
of trainable parameters of the matched SAE and of the DualSAE (the TopK baseline has tied
weights, so its matched arm is dimension-matched rather than parameter-matched; see
scripts/param_matched/train_param_matched.py).

Usage
-----
    python analysis/main/build_param_matched_table.py --long ./outputs/main/main_long.csv \\
        --latex ./outputs/main/param_matched_table.tex --markdown ./outputs/main/param_matched_table.md
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

_HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(_HERE))
import main_analysis_common as A  # noqa: E402

VISION = _HERE.parents[1]
ACTS = (("topk", "TopK"), ("batch_topk", "BatchTopK"), ("jumprelu", "JumpReLU"))
ENC_ORDER = (("vit", "ViT"), ("clip", "CLIP"), ("sigclip", "SigLIP2"))


def param_counts() -> dict:
    """{(encoder, act): (params of the matched SAE, params of the DualSAE at 8192)}."""
    sys.path.insert(0, str(VISION / "scripts" / "param_matched"))
    sys.path.insert(0, str(VISION))
    import torch
    from train_param_matched import ENCODER_ACT_SIZE, matched_n_latents, DUAL_OF
    from models.topk_sae import TopKSAE, TopK
    from models.batch_topk_sae import BatchTopKSAE
    from models.jumprelu_sae import JumpReLUSAE
    from models.dual_sae import DualSAE
    torch.set_num_threads(1)

    def cfg(act, n, **kw):
        d = dict(act_size=act, dict_size=n, seed=42, device="cpu", dtype=torch.float32, top_k=64,
                 l1_coeff=1e-4, bandwidth=1e-3, n_batches_to_dead=4882, input_unit_norm=False,
                 aux_penalty=1 / 32, top_k_aux=64)
        d.update(kw)
        return d

    def n_params(m):
        return sum(p.numel() for p in m.parameters())

    out = {}
    for enc, act in ENCODER_ACT_SIZE.items():
        for m, _ in ACTS:
            n = matched_n_latents(enc, m)
            base = (TopKSAE(n_latents=n, n_inputs=act, activation=TopK(64), tied=True, normalize=True)
                    if m == "topk" else (BatchTopKSAE if m == "batch_topk" else JumpReLUSAE)(cfg(act, n)))
            dual = DualSAE(cfg(act, 8192, sparsity_mode=DUAL_OF[m][len("dual_"):],
                               poly_hidden=512, poly_layers=1))
            out[(enc, m)] = (n_params(base), n_params(dual))
    return out


def _fmt_m(n: int) -> str:
    return f"{n / 1e6:.1f}M"


def build(long: dict, counts: dict) -> tuple:
    tex = [r"% Generated by analysis/main/build_param_matched_table.py",
           r"\begin{tabular}{llcc" + "ccccc" * len(A.DATASETS) + "}", r"\toprule",
           r"\textbf{Encoder} & \textbf{Activation} & \textbf{Par. (SAE)} & \textbf{Par. (DualSAE)} & "
           + " & ".join(" & ".join(rf"$\Delta${A.METRIC_LABEL[m]}" for m in A.METRICS) for _ in A.DATASETS)
           + r" \\", r"\midrule"]
    md = ["| Encoder | Activation | Par. (SAE) | Par. (DualSAE) | "
          + " | ".join(f"{A.DATASET_SHORT[d]} Δ{m}" for d in A.DATASETS for m in A.METRICS) + " |",
          "|---|---|---:|---:|" + "---:|" * (5 * len(A.DATASETS))]
    for enc, enc_label in ENC_ORDER:
        for act, act_label in ACTS:
            cells = []
            for ds in A.DATASETS:
                for metric in A.METRICS:
                    a = long.get((ds, enc, f"{act}_pmatch", metric))
                    b = long.get((ds, enc, {"topk": "dual_topk", "batch_topk": "dual_batch_topk",
                                            "jumprelu": "dual_jump_relu"}[act], metric))
                    if a and b and a["mean"] is not None and b["mean"] is not None:
                        cells.append(f"{a['mean'] - b['mean']:+.3f}")
                    else:
                        cells.append("---")
            pb, pd = counts.get((enc, act), (None, None))
            par = [(_fmt_m(pb) if pb else "---"), (_fmt_m(pd) if pd else "---")]
            tex.append(f"{enc_label} & {act_label} & " + " & ".join(par + cells) + r" \\")
            md.append(f"| {enc_label} | {act_label} | " + " | ".join(par + cells) + " |")
        tex.append(r"\midrule" if enc != ENC_ORDER[-1][0] else r"\bottomrule")
    tex.append(r"\end{tabular}")
    return tex, md


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--long", default="./outputs/main/main_long.csv")
    ap.add_argument("--latex", default="./outputs/main/param_matched_table.tex")
    ap.add_argument("--markdown", default="./outputs/main/param_matched_table.md")
    ap.add_argument("--no_param_counts", action="store_true", help="skip instantiating models")
    args = ap.parse_args()
    long = A.load_long(Path(args.long))
    counts = {} if args.no_param_counts else param_counts()
    tex, md = build(long, counts)
    for path, lines in ((args.latex, tex), (args.markdown, md)):
        if path:
            Path(path).parent.mkdir(parents=True, exist_ok=True)
            Path(path).write_text("\n".join(lines) + "\n")
            print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
