#!/usr/bin/env python3
"""Supplementary table: every SAE variant next to its DualSAE twin, ImageNet-1K and OpenImagesV7.

Reads the long CSV of ``collect_main.py`` and writes the side-by-side table (rows: encoder x
method, in pairs; columns: R^2, MS, Pur., KNN, LP for each dataset; cells: mean with the
sample standard deviation over seeds). Within each pair and column the larger mean is set in
bold. Output formats: LaTeX (``--latex``, uses the macros ``\\stdval{m}{s}``, ``\\stdbf{m}{s}``
and ``\\dc{...}`` for the DualSAE rows -- definitions are written as a comment at the top) and
Markdown (``--markdown``).

Rows: TK / D-TK, BTK / D-BTK, JR / D-JR, MAT / D-MAT, GATE / D-GATE, CB / CB-DUAL. A cell with
no data prints as ``---``.

Usage
-----
    python analysis/main/build_main_table.py --long ./outputs/main/main_long.csv \\
        --latex ./outputs/main/main_table.tex --markdown ./outputs/main/main_table.md
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import main_analysis_common as A  # noqa: E402

ENC_SHORT = {"vit": "ViT", "clip": "CLIP", "sigclip": "SL2"}
LATEX_HEADER = r"""% Generated by analysis/main/build_main_table.py from the collector's long CSV.
% Macros used below (define them in the preamble), e.g.:
%   \newcommand{\stdval}[2]{#1{\tiny$\pm$#2}}
%   \newcommand{\stdbf}[2]{\textbf{#1}{\tiny$\pm$#2}}
%   \newcommand{\dc}[1]{\cellcolor{dualrow}#1}
"""


def _cell(long, ds, enc, method, metric):
    r = long.get((ds, enc, method, metric))
    if not r or r["mean"] is None:
        return None, None
    return r["mean"], r["sd"]


def build(long: dict, datasets=A.DATASETS, encoders=A.ENCODER_ORDER) -> tuple:
    """(latex lines, markdown lines)."""
    tex = [LATEX_HEADER.rstrip("\n"), r"\begin{tabular}{ll" + "ccccc" * len(datasets) + "}", r"\toprule"]
    tex.append(" & & " + " & ".join(rf"\multicolumn{{5}}{{c}}{{\textbf{{{A.DATASET_SHORT[d]}}}}}" for d in datasets) + r" \\")
    tex.append(r"\textbf{Enc.} & \textbf{SAE} & " + " & ".join(
        " & ".join(A.METRIC_LABEL[m] for m in A.METRICS) for _ in datasets) + r" \\")
    tex.append(r"\midrule")
    md = ["| Enc. | SAE | " + " | ".join(f"{A.DATASET_SHORT[d]} {m}" for d in datasets for m in A.METRICS) + " |",
          "|---|---|" + "---:|" * (5 * len(datasets))]
    for enc in encoders:
        for pi, (base, dual, _title) in enumerate(A.PAIRS):
            for method in (base, dual):
                tcells, mcells = [], []
                for ds in datasets:
                    for metric in A.METRICS:
                        m, sd = _cell(long, ds, enc, method, metric)
                        other = dual if method == base else base
                        om, _ = _cell(long, ds, enc, other, metric)
                        best = m is not None and (om is None or m >= om)
                        sd_s = A.fmt_num(sd) if sd is not None else "---"
                        if m is None:
                            tcells.append("---")
                            mcells.append("---")
                        else:
                            macro = r"\stdbf" if best else r"\stdval"
                            t = f"{macro}{{{m:.4f}}}{{{sd_s}}}"
                            tcells.append(rf"\dc{{{t}}}" if method == dual else t)
                            mcells.append((f"**{m:.4f}**" if best else f"{m:.4f}") + f" ± {sd_s}")
                label = A.LABEL[method]
                lab_t = rf"\dc{{{label}}}" if method == dual else label
                enc_t = rf"\multirow{{12}}{{*}}{{\rotatebox[origin=c]{{90}}{{\textbf{{{ENC_SHORT[enc]}}}}}}}" \
                    if (pi == 0 and method == base) else ""
                tex.append(f"{enc_t} & {lab_t} & " + " & ".join(tcells) + r" \\")
                md.append(f"| {ENC_SHORT[enc] if (pi == 0 and method == base) else ''} | {label} | "
                          + " | ".join(mcells) + " |")
            if pi < len(A.PAIRS) - 1:
                tex.append(r"\cmidrule(lr){2-" + str(2 + 5 * len(datasets)) + "}")
        tex.append(r"\midrule" if enc != encoders[-1] else r"\bottomrule")
    tex.append(r"\end{tabular}")
    return tex, md


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--long", default="./outputs/main/main_long.csv")
    ap.add_argument("--latex", default="./outputs/main/main_table.tex")
    ap.add_argument("--markdown", default="./outputs/main/main_table.md")
    ap.add_argument("--checkpoint", default="best")
    args = ap.parse_args()
    long = A.load_long(Path(args.long), checkpoint=args.checkpoint)
    tex, md = build(long)
    for path, lines in ((args.latex, tex), (args.markdown, md)):
        if path:
            Path(path).parent.mkdir(parents=True, exist_ok=True)
            Path(path).write_text("\n".join(lines) + "\n")
            print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
